# suffixes. The dictionary carries duplicate stressed/unstressed entries for
# many forms, hence the doubled alternatives. Order matters: broader groups
# are checked first UNLESS a shorter alternative would shadow a more specific
# one in a smaller group (e.g. -ього from -ький would otherwise swallow
