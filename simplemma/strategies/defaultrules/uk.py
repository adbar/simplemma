# closed classes where the productive declension/conjugation collides with an
# irregular lemma: xто-pronouns declining like -кий adjectives, and a couple
# of -вало/-вати homographs that are really nouns/adjectives.
_EXCLUDED = frozenset(
    {
        "аби́ким",
        "аби́кого",
        "де́ким",
        "де́кого",
        "де́кім",
        "деким",
        "декого",
        "декім",
        "нікого",
        "ніким",
        "зухва́ло",
        "ухва́ло",
    }
)


def apply_uk(token: str) -> str | None:
    "Apply pre-defined rules for Ukrainian."
    if len(token) < 6 or token[0].isupper() or "-" in token or token in _EXCLUDED:
        return None

    return apply_rules(token, DEFAULT_RULES)
